import 'dart:io';

import 'package:drift/drift.dart' as drift;
import 'package:drift/native.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:lotus_erp/database/db/app_database.dart';
import 'package:lotus_erp/models/girvi/girvi_notice_action_model.dart';
import 'package:lotus_erp/repositories/girvi/girvi_notice_action_repository.dart';
import 'package:lotus_erp/repositories/girvi/girvi_notice_document_repository.dart';

void main() {
  late AppDatabase db;
  late GirviNoticeActionRepository actions;
  late int loanId;
  const texts = {
    GirviNoticeLanguage.hindi: 'गिरवी सूचना: कृपया दुकान पर संपर्क करें।',
    GirviNoticeLanguage.english:
        'Pledge account notice: Please contact the branch.',
  };

  setUp(() async {
    db = AppDatabase.forTesting(NativeDatabase.memory());
    actions = GirviNoticeActionRepository(db);
    final customerId = await db.into(db.customers).insert(
          CustomersCompanion.insert(
              name: 'Notice Customer', mobile: '9000000000'),
        );
    loanId = await db.into(db.girviLoans).insert(
          GirviLoansCompanion.insert(
            ticketNo: 'GRV-LANGUAGE-001',
            customerId: customerId,
            itemDescription: 'Gold ring',
            loanAmount: const drift.Value(10000),
            startDate: drift.Value(DateTime(2025, 1, 1)),
            maturityDate: drift.Value(DateTime(2025, 7, 1)),
            status: const drift.Value('OVERDUE'),
          ),
        );
  });
  tearDown(() async => db.close());

  Future<int> approve({Map<GirviNoticeLanguage, String> documents = texts}) =>
      actions.recordNoticePrepared(
        girviId: loanId,
        noticeType: GirviNoticeType.formal,
        noticeText: texts[GirviNoticeLanguage.hindi]!,
        primaryLanguage: GirviNoticeLanguage.hindi,
        noticePeriodDays: 7,
        noticeDocuments: documents,
        autoGeneratedDocuments: texts,
      );

  test('saves both approved texts with independent edits and hashes', () async {
    final actionId = await approve(documents: {
      ...texts,
      GirviNoticeLanguage.english: 'Edited English notice for this customer.',
    });
    final documents =
        (await GirviNoticeDocumentRepository(db).byGirviIds([loanId]))[loanId]!;
    expect(documents, hasLength(2));
    final hindi =
        documents.singleWhere((d) => d.language == GirviNoticeLanguage.hindi);
    final english =
        documents.singleWhere((d) => d.language == GirviNoticeLanguage.english);
    expect(hindi.noticeActionId, actionId);
    expect(english.noticeActionId, actionId);
    expect(hindi.noticeText, texts[GirviNoticeLanguage.hindi]);
    expect(hindi.wasManuallyEdited, isFalse);
    expect(english.wasManuallyEdited, isTrue);
    expect(english.generatedText, texts[GirviNoticeLanguage.english]);
    expect(english.documentHash, isNot(hindi.documentHash));
    expect((await db.select(db.girviNoticeActions).get()), hasLength(1));
  });

  test('rejects approval without an English document', () async {
    await expectLater(
        approve(documents: {
          GirviNoticeLanguage.hindi: texts[GirviNoticeLanguage.hindi]!
        }),
        throwsArgumentError);
    expect(await db.select(db.girviNoticeActions).get(), isEmpty);
    expect(await db.select(db.girviNoticeDocuments).get(), isEmpty);
  });

  test('approves the English-only document used by Prepare Notice', () async {
    final english = texts[GirviNoticeLanguage.english]!;
    await actions.recordNoticePrepared(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeText: english,
      primaryLanguage: GirviNoticeLanguage.english,
      noticePeriodDays: 7,
      noticeDocuments: {GirviNoticeLanguage.english: english},
      autoGeneratedDocuments: {GirviNoticeLanguage.english: english},
    );

    final documents = await db.select(db.girviNoticeDocuments).get();
    expect(documents, hasLength(1));
    expect(documents.single.language, 'english');
    await actions.recordNoticeDeliveryProof(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeText: english,
      noticeLanguage: GirviNoticeLanguage.english,
      actionType: GirviNoticeActionTypes.noticePdfPrinted,
      deliveryChannel: 'Printer',
      deliveryStatus: 'Printed',
    );
  });

  test('corrected compound notice retains the earlier approved document',
      () async {
    const simple = 'Simple Interest Breakdown\nInterest Outstanding: ₹ 52,500';
    const compound =
        'Compound Interest Breakdown\nInterest Outstanding: ₹ 1,08,120';
    final originalId = await actions.recordNoticePrepared(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeText: simple,
      noticePeriodDays: 7,
      noticeDocuments: {GirviNoticeLanguage.english: simple},
    );
    await expectLater(
      actions.recordNoticePrepared(
        girviId: loanId,
        noticeType: GirviNoticeType.formal,
        noticeText: compound,
        noticePeriodDays: 7,
        noticeDocuments: {GirviNoticeLanguage.english: compound},
      ),
      throwsStateError,
    );
    final correctedId = await actions.recordNoticePrepared(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeText: compound,
      noticePeriodDays: 7,
      noticeDocuments: {GirviNoticeLanguage.english: compound},
      supersedesNoticeActionId: originalId,
    );
    final records = await db.select(db.girviNoticeActions).get();
    expect(records, hasLength(2));
    expect(records.singleWhere((row) => row.id == correctedId).noticeActionId,
        originalId);
    final documents = await db.select(db.girviNoticeDocuments).get();
    expect(documents.map((row) => row.noticeText).toSet(), {simple, compound});
    await actions.recordNoticeDeliveryProof(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeText: compound,
      noticeLanguage: GirviNoticeLanguage.english,
      noticeActionId: correctedId,
      actionType: GirviNoticeActionTypes.noticePdfPrinted,
      deliveryChannel: 'Printer',
      deliveryStatus: 'Printed',
    );
  });

  test('primary language text must match its saved document', () async {
    await expectLater(
      actions.recordNoticePrepared(
        girviId: loanId,
        noticeType: GirviNoticeType.formal,
        noticeText: texts[GirviNoticeLanguage.hindi]!,
        primaryLanguage: GirviNoticeLanguage.english,
        noticePeriodDays: 7,
        noticeDocuments: texts,
      ),
      throwsArgumentError,
    );
    expect(await db.select(db.girviNoticeActions).get(), isEmpty);
  });

  test('document insert failure rolls back approval and both languages',
      () async {
    await db.customStatement('''
CREATE TRIGGER reject_english_document BEFORE INSERT ON girvi_notice_documents
WHEN NEW.language = 'english'
BEGIN SELECT RAISE(ABORT, 'Simulated document write failure'); END;
''');
    await expectLater(approve(), throwsA(isA<Exception>()));
    expect(await db.select(db.girviNoticeActions).get(), isEmpty);
    expect(await db.select(db.girviNoticeDocuments).get(), isEmpty);
  });

  test('delivery accepts each approved language but rejects mismatched text',
      () async {
    await approve();
    for (final language in GirviNoticeLanguage.values) {
      await actions.recordNoticeDeliveryProof(
        girviId: loanId,
        noticeType: GirviNoticeType.formal,
        noticeText: texts[language]!,
        noticeLanguage: language,
        actionType: GirviNoticeActionTypes.noticePdfSaved,
        deliveryChannel: 'PDF File',
        deliveryStatus: 'Saved',
      );
    }
    await expectLater(
      actions.recordNoticeDeliveryProof(
        girviId: loanId,
        noticeType: GirviNoticeType.formal,
        noticeText: texts[GirviNoticeLanguage.hindi]!,
        noticeLanguage: GirviNoticeLanguage.english,
        actionType: GirviNoticeActionTypes.noticePdfSaved,
        deliveryChannel: 'PDF File',
        deliveryStatus: 'Saved',
      ),
      throwsStateError,
    );
    expect(await db.select(db.girviNoticeActions).get(), hasLength(3));
  });

  test('legacy notice remains single-language; cannot relabel it English',
      () async {
    await actions.recordNoticePrepared(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeText: texts[GirviNoticeLanguage.hindi]!,
      noticePeriodDays: 7,
    );
    expect(await db.select(db.girviNoticeDocuments).get(), isEmpty);
    await expectLater(
      actions.recordNoticeDeliveryProof(
        girviId: loanId,
        noticeType: GirviNoticeType.formal,
        noticeText: texts[GirviNoticeLanguage.hindi]!,
        noticeLanguage: GirviNoticeLanguage.english,
        actionType: GirviNoticeActionTypes.noticePdfPrinted,
        deliveryChannel: 'Printer',
        deliveryStatus: 'Printed',
      ),
      throwsStateError,
    );
  });

  test('v57 upgrade preserves legacy approval and creates bilingual storage',
      () async {
    final directory =
        await Directory.systemTemp.createTemp('lotus_notice_migration_');
    final file = File('${directory.path}/test.sqlite');
    var migrationDb = AppDatabase.forTesting(NativeDatabase(file));
    try {
      final customer = await migrationDb.into(migrationDb.customers).insert(
            CustomersCompanion.insert(
                name: 'Migration Customer', mobile: '9000000001'),
          );
      final loan = await migrationDb.into(migrationDb.girviLoans).insert(
            GirviLoansCompanion.insert(
                ticketNo: 'GRV-MIGRATION',
                customerId: customer,
                itemDescription: 'Ring',
                loanAmount: const drift.Value(10000),
                startDate: drift.Value(DateTime(2025, 1, 1)),
                maturityDate: drift.Value(DateTime(2025, 7, 1)),
                status: const drift.Value('OVERDUE')),
          );
      final noticeId =
          await GirviNoticeActionRepository(migrationDb).recordNoticePrepared(
        girviId: loan,
        noticeType: GirviNoticeType.formal,
        noticeText: texts[GirviNoticeLanguage.hindi]!,
        noticePeriodDays: 7,
      );
      await migrationDb.customStatement('DROP TABLE girvi_notice_documents');
      await migrationDb.customStatement('PRAGMA user_version = 57');
      await migrationDb.close();
      migrationDb = AppDatabase.forTesting(NativeDatabase(file));
      final saved =
          await migrationDb.select(migrationDb.girviNoticeActions).get();
      expect(saved.single.id, noticeId);
      expect(saved.single.noticeText, texts[GirviNoticeLanguage.hindi]);
      expect(await migrationDb.select(migrationDb.girviNoticeDocuments).get(),
          isEmpty);
      await migrationDb.into(migrationDb.girviNoticeDocuments).insert(
            GirviNoticeDocumentsCompanion.insert(
              girviId: loan,
              noticeActionId: noticeId,
              noticeStage: 1,
              language: 'hindi',
              noticeText: texts[GirviNoticeLanguage.hindi]!,
              documentHash: saved.single.documentHash!,
            ),
          );
      final document =
          (await migrationDb.select(migrationDb.girviNoticeDocuments).get())
              .single;
      expect(document.createdAt.difference(DateTime.now()).inSeconds.abs(),
          lessThan(10));
      final version =
          await migrationDb.customSelect('PRAGMA user_version').getSingle();
      expect(version.read<int>('user_version'), 60);
    } finally {
      await migrationDb.close();
      await directory.delete(recursive: true);
    }
  });
}
