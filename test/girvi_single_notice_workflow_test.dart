      throwsStateError,
    );
  });

  test('notice review starts on confirmed delivery; recovery is explicit',
      () async {
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);
    final noticeId = await approve();
    final deadline = clock.add(const Duration(days: 7));
    clock = deadline.subtract(const Duration(seconds: 1));
    expect(_case(loanId, clock, await history()).stage,
        ContactRecoveryStage.noticePending);
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);
    clock = deadline;
    final undelivered = _case(loanId, clock, await history());
    expect(undelivered.stage, ContactRecoveryStage.noticePending);
    expect(undelivered.nextNoticeType, isNull);
    expect((await history()).where((row) => row.isCollateralRecoveryInitiated),
        isEmpty);
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);
    await expectLater(
      repository.recordNoticeDeliveryProof(
        girviId: loanId,
        noticeType: GirviNoticeType.formal,
        noticeActionId: noticeId,
        noticeText: english,
        actionType: GirviNoticeActionTypes.noticeDeliveryRecorded,
        deliveryChannel: 'In person',
        deliveryStatus: 'Delivered',
        deliveryReference: '',
      ),
      throwsArgumentError,
    );
    await confirmDelivery(noticeId, english);
    final customerDeadline = clock.add(const Duration(days: 7));
    clock = customerDeadline.subtract(const Duration(seconds: 1));
    expect(_case(loanId, clock, await history()).stage,
        ContactRecoveryStage.noticePending);
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);
    clock = customerDeadline;
    expect(_case(loanId, clock, await history()).stage,
        ContactRecoveryStage.disposalReady);
    await repository.recordCollateralRecoveryInitiated(girviId: loanId);
    expect(_case(loanId, clock, await history()).stage,
        ContactRecoveryStage.recoveryInProgress);
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);
  });

  test('repaid accounts reject recovery even with an expired notice', () async {
