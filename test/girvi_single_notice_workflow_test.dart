void main() {
  late AppDatabase db;
  late GirviNoticeActionRepository repository;
  late int loanId;
  late DateTime clock;
  const english = 'PLEDGE ACCOUNT NOTICE\nApproved English text.';
  const hindi = 'गिरवी खाता सूचना\nस्वीकृत हिंदी विवरण।';
  const documents = {
    GirviNoticeLanguage.english: english,
    GirviNoticeLanguage.hindi: hindi,
  };

  setUp(() async {
    db = AppDatabase.forTesting(NativeDatabase.memory());
    loanId = await _seedLoan(db);
    clock = DateTime(2026, 10, 17, 12, 30);
    repository = GirviNoticeActionRepository(db, now: () => clock);
  });
  tearDown(() => db.close());

  Future<int> approve({int days = 7}) => repository.recordNoticePrepared(
        girviId: loanId,
        noticeType: GirviNoticeType.formal,
        noticeText: english,
        noticePeriodDays: days,
        noticeDocuments: documents,
        autoGeneratedDocuments: documents,
      );
  Future<void> confirmDelivery(int noticeId, String noticeText) async {
    await repository.recordNoticeDeliveryProof(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeActionId: noticeId,
      noticeText: noticeText,
      actionType: GirviNoticeActionTypes.noticePdfPrinted,
      deliveryChannel: 'Printer',
      deliveryStatus: 'Printed',
      deliveryReference: 'PRINT-$noticeId',
    );
    await repository.recordNoticeDeliveryProof(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeActionId: noticeId,
      noticeText: noticeText,
      actionType: GirviNoticeActionTypes.noticeDeliveryRecorded,
      deliveryChannel: 'In person',
      deliveryStatus: 'Delivered',
      deliveryReference: 'ACK-$noticeId',
    );
  }

  Future<List<GirviNoticeAction>> history() async =>
      (await repository.actionsByGirviIds([loanId]))[loanId] ?? [];

  test('only one notice type can be generated and approved per account',
      () async {
    expect(GirviNoticeType.values, [GirviNoticeType.formal]);
    final id = await approve();
    await expectLater(approve(), throwsStateError);
    expect(await db.select(db.girviNoticeActions).get(), hasLength(1));
    final saved = await db.select(db.girviNoticeDocuments).get();
    expect(saved, hasLength(2));
    expect(saved.map((row) => row.noticeActionId).toSet(), {id});
    expect(saved.map((row) => row.noticeText).toSet(), {english, hindi});
    // The database also rejects callers that bypass repository validation.
    await expectLater(
        db.into(db.girviNoticeActions).insert(
            GirviNoticeActionsCompanion.insert(
                girviId: loanId,
                actionType: GirviNoticeActionTypes.noticePrepared)),
        throwsA(isA<Exception>()));
  });

  test('approved shop snapshot persists with the notice action', () async {
    const snapshot = '{"version":1,"shopName":"Anjali Jewellers"}';
    final id = await repository.recordNoticePrepared(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeText: english,
      noticePeriodDays: 7,
      noticeDocuments: documents,
      brandingSnapshot: snapshot,
    );
    final action = (await history()).single;
    expect(action.id, id);
    expect(action.brandingSnapshot, snapshot);
    expect(
        (await db.select(db.girviNoticeActions).get()).single.brandingSnapshot,
        snapshot);
  });

  test('selected response days begin after confirmed delivery', () async {
    final noticeId = await approve(days: 14);
    final approved = (await history()).single;
    expect(approved.noticeDeadlineAt, clock.add(const Duration(days: 14)));
    clock = clock.add(const Duration(days: 2));
    await confirmDelivery(noticeId, english);
    final deliveryDeadline = clock.add(const Duration(days: 14));
    clock = deliveryDeadline.subtract(const Duration(seconds: 1));
    expect(_case(loanId, clock, await history()).stage,
        ContactRecoveryStage.noticePending);
    clock = deliveryDeadline;
    expect(_case(loanId, clock, await history()).stage,
        ContactRecoveryStage.disposalReady);
  });

  test('PDF share alone does not start the response period', () async {
    final noticeId = await approve(days: 14);
    await repository.recordNoticeDeliveryProof(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeActionId: noticeId,
      noticeText: english,
      actionType: GirviNoticeActionTypes.noticePdfShared,
      deliveryChannel: 'WhatsApp',
      deliveryStatus: 'Shared',
      deliveryReference: 'WhatsApp: 9304479436',
    );

    clock = clock.add(const Duration(days: 15));
    expect(_case(loanId, clock, await history()).stage,
        ContactRecoveryStage.noticePending);
    await expectLater(
      repository.recordCollateralRecoveryInitiated(girviId: loanId),
      throwsStateError,
    );

    await confirmDelivery(noticeId, english);

    clock = clock.add(const Duration(days: 13, hours: 23));
    expect(_case(loanId, clock, await history()).stage,
        ContactRecoveryStage.noticePending);
    await expectLater(
      repository.recordCollateralRecoveryInitiated(girviId: loanId),
      throwsStateError,
    );

    clock = DateTime(2026, 11, 15, 12, 30);
    final ready = _case(loanId, clock, await history());
    expect(ready.stage, ContactRecoveryStage.disposalReady);
    expect(ready.canInitiateCollateralRecovery, isTrue);
    await repository.recordCollateralRecoveryInitiated(girviId: loanId);
    expect(_case(loanId, clock, await history()).stage,
        ContactRecoveryStage.recoveryInProgress);
  });

  test('customer recovery request is accepted after confirmed delivery',
      () async {
    final noticeId = await approve();
    await confirmDelivery(noticeId, english);
    final responses = GirviCustomerResponseRepository(db, now: () => clock);
    await responses.record(
      girviId: loanId,
      noticeActionId: noticeId,
      kind: GirviCustomerResponseKind.recoveryRequest,
      channel: GirviContactChannel.phoneCall,
      responseText: 'Customer requested recovery settlement.',
    );
    final replies = (await responses.byGirviIds([loanId]))[loanId]!;
    expect(
        _case(loanId, clock, await history(), responses: replies)
            .canInitiateCollateralRecovery,
        isTrue);
    await repository.recordCollateralRecoveryInitiated(girviId: loanId);
  });

  test('an open hold protects the whole selected date in UI and database',
      () async {
    final noticeId = await approve();
    await confirmDelivery(noticeId, english);
    final responses = GirviCustomerResponseRepository(db, now: () => clock);
    await responses.record(
      girviId: loanId,
      noticeActionId: noticeId,
      kind: GirviCustomerResponseKind.holdRequest,
      channel: GirviContactChannel.phoneCall,
      responseText: 'Customer requested hold through 28 October.',
      promiseDueAt: DateTime(2026, 10, 28),
    );
    clock = DateTime(2026, 10, 28, 15);
    final replies = (await responses.byGirviIds([loanId]))[loanId]!;
    expect(
        _case(loanId, clock, await history(), responses: replies)
            .canInitiateCollateralRecovery,
        isFalse);
    await expectLater(
      repository.recordCollateralRecoveryInitiated(girviId: loanId),
      throwsStateError,
    );
    clock = DateTime(2026, 10, 29);
    expect(
        _case(loanId, clock, await history(), responses: replies)
            .canInitiateCollateralRecovery,
        isTrue);
    await repository.recordCollateralRecoveryInitiated(girviId: loanId);
  });

  test('a reply requires delivery and no-response requires the full period',
      () async {
    final noticeId = await approve();
    final responses = GirviCustomerResponseRepository(db, now: () => clock);
    await expectLater(
      responses.record(
        girviId: loanId,
        noticeActionId: noticeId,
        kind: GirviCustomerResponseKind.willVisit,
        channel: GirviContactChannel.phoneCall,
        responseText: 'Will visit.',
        promiseDueAt: DateTime(2026, 10, 20),
      ),
      throwsStateError,
    );
    await confirmDelivery(noticeId, english);
    await expectLater(
      responses.record(
        girviId: loanId,
        noticeActionId: noticeId,
        kind: GirviCustomerResponseKind.noResponse,
        channel: GirviContactChannel.other,
        responseText: 'No response.',
      ),
      throwsStateError,
    );
    clock = clock.add(const Duration(days: 7));
    await responses.record(
      girviId: loanId,
      noticeActionId: noticeId,
      kind: GirviCustomerResponseKind.noResponse,
      channel: GirviContactChannel.other,
