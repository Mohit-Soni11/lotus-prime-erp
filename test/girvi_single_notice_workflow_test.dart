import 'package:lotus_erp/repositories/girvi/girvi_notice_document_repository.dart';

void main() {
  late AppDatabase db;
  late GirviNoticeActionRepository repository;
  late int loanId;
  late DateTime clock;
  const english = 'PLEDGE ACCOUNT NOTICE\nApproved English text.';
  const hindi = 'गिरवी खाता सूचना\nस्वीकृत हिंदी विवरण।';
  const documents = {
    GirviNoticeLanguage.english: english,
    GirviNoticeLanguage.hindi: hindi,
  };

  setUp(() async {
    db = AppDatabase.forTesting(NativeDatabase.memory());
    loanId = await _seedLoan(db);
    clock = DateTime(2026, 10, 17, 12, 30);
    repository = GirviNoticeActionRepository(db, now: () => clock);
  });
  tearDown(() => db.close());

  Future<int> approve() => repository.recordNoticePrepared(
        girviId: loanId,
        noticeType: GirviNoticeType.formal,
        noticeText: english,
        noticePeriodDays: 7,
        noticeDocuments: documents,
        autoGeneratedDocuments: documents,
      );
  Future<List<GirviNoticeAction>> history() async =>
      (await repository.actionsByGirviIds([loanId]))[loanId] ?? [];

  test('only one notice type can be generated and approved per account',
      () async {
    expect(GirviNoticeType.values, [GirviNoticeType.formal]);
    final id = await approve();
    await expectLater(approve(), throwsStateError);
    expect(await db.select(db.girviNoticeActions).get(), hasLength(1));
    final saved = await db.select(db.girviNoticeDocuments).get();
    expect(saved, hasLength(2));
    expect(saved.map((row) => row.noticeActionId).toSet(), {id});
    expect(saved.map((row) => row.noticeText).toSet(), {english, hindi});
    // The database also rejects callers that bypass repository validation.
    await expectLater(
        db.into(db.girviNoticeActions).insert(
            GirviNoticeActionsCompanion.insert(
                girviId: loanId,
                actionType: GirviNoticeActionTypes.noticePrepared)),
        throwsA(isA<Exception>()));
  });

  test('one notice reaches review at its exact deadline; recovery is explicit',
      () async {
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);
    await approve();
    final deadline = clock.add(const Duration(days: 7));
    clock = deadline.subtract(const Duration(seconds: 1));
    expect(_case(loanId, clock, await history()).stage,
        ContactRecoveryStage.noticePending);
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);
    clock = deadline;
    final ready = _case(loanId, clock, await history());
    expect(ready.stage, ContactRecoveryStage.disposalReady);
    expect(ready.nextNoticeType, isNull);
    expect((await history()).where((row) => row.isCollateralRecoveryInitiated),
        isEmpty);
    await repository.recordCollateralRecoveryInitiated(girviId: loanId);
    expect(_case(loanId, clock, await history()).stage,
        ContactRecoveryStage.recoveryInProgress);
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);
  });

  test('repaid accounts reject recovery even with an expired notice', () async {
    await approve();
    clock = clock.add(const Duration(days: 8));
    await (db.update(db.girviLoans)..where((row) => row.id.equals(loanId)))
        .write(const GirviLoansCompanion(status: drift.Value('RELEASED')));
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);
  });

  test('retired stages are unavailable through the generic action API',
      () async {
    for (final actionType in GirviNoticeHistory.preparationTypes) {
      await expectLater(
          repository.recordAction(girviId: loanId, actionType: actionType),
          throwsStateError);
    }
    expect(await db.select(db.girviNoticeActions).get(), isEmpty);
  });

  test('old reminders stay in history and do not become recovery authority',
      () async {
    await _legacy(db, loanId, 1, clock.subtract(const Duration(days: 90)));
    await _legacy(db, loanId, 2, clock.subtract(const Duration(days: 60)));
    final before = _case(loanId, clock, await history());
    expect(before.legacyNoticeActions, hasLength(2));
    expect(before.stage, ContactRecoveryStage.noticeRequired);
    expect(before.canPrepareNotice, isTrue);
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);
    await approve();
    final after = _case(loanId, clock, await history());
    expect(after.formalNoticeAction, isNotNull);
    expect(after.legacyNoticeActions, hasLength(2));
    expect(after.stage, ContactRecoveryStage.noticePending);
    await expectLater(approve(), throwsStateError);
  });

  test('legacy final notice retains its deadline without requiring another',
      () async {
    await _legacy(db, loanId, 3, clock,
        deadline: clock.add(const Duration(days: 10)));
    final pending = _case(loanId, clock, await history());
    expect(pending.stage, ContactRecoveryStage.noticePending);
    expect(pending.nextNoticeType, isNull);
    expect(pending.formalNoticeAction, isNull);
    expect(pending.recoveryNoticeAction!.noticeLabel, 'Final Notice');
    await expectLater(approve(), throwsStateError);
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);
    clock = clock.add(const Duration(days: 10));
    await repository.recordCollateralRecoveryInitiated(girviId: loanId);
  });

  test('old and new stage-one replies and proofs remain linked to their notice',
      () async {
    final oldId =
        await _legacy(db, loanId, 1, clock.subtract(const Duration(days: 40)));
    final formalId = await approve();
    final responses = GirviCustomerResponseRepository(db);
    for (final id in [oldId, formalId]) {
      await responses.record(
          girviId: loanId,
          noticeActionId: id,
          kind: GirviCustomerResponseKind.other,
          channel: GirviContactChannel.phoneCall,
          responseText: 'Response for notice $id');
    }
    await repository.recordNoticeDeliveryProof(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeActionId: oldId,
      noticeText: 'Legacy notice 1',
      actionType: GirviNoticeActionTypes.noticePdfSaved,
      deliveryChannel: 'PDF File',
      deliveryStatus: 'Saved',
    );
    await repository.recordNoticeDeliveryProof(
      girviId: loanId,
      noticeType: GirviNoticeType.formal,
      noticeActionId: formalId,
      noticeLanguage: GirviNoticeLanguage.hindi,
      noticeText: hindi,
      actionType: GirviNoticeActionTypes.noticePdfPrinted,
      deliveryChannel: 'Printer',
      deliveryStatus: 'Printed',
    );
    final records =
        await GirviNoticeDocumentRepository(db).byGirviIds([loanId]);
    final item = _case(loanId, clock, await history(),
        responses: (await responses.byGirviIds([loanId]))[loanId]!,
        documents: records[loanId]!);
    final old = item.legacyNoticeActions.single;
    final formal = item.formalNoticeAction!;
    expect(item.responsesForNotice(old).single.noticeActionId, oldId);
    expect(item.responsesForNotice(formal).single.noticeActionId, formalId);
    expect(item.latestDeliveryProofForNotice(old)!.deliveryStatus, 'Saved');
    expect(
        item.latestDeliveryProofForNotice(formal)!.deliveryStatus, 'Printed');
    expect(item.noticeStatusLabel, 'Approved');
    expect(item.noticeStatusLabel, isNot(contains('Sent')));
    await expectLater(
        repository.recordNoticeDeliveryProof(
          girviId: loanId,
          noticeType: GirviNoticeType.formal,
          noticeActionId: oldId,
          noticeText: english,
          actionType: GirviNoticeActionTypes.noticePdfSaved,
          deliveryChannel: 'PDF File',
          deliveryStatus: 'Saved',
        ),
        throwsStateError);
  });

  test('identical old and new texts do not share their delivery records',
      () async {
    final oldId =
        await _legacy(db, loanId, 1, clock.subtract(const Duration(days: 40)));
    await (db.update(db.girviNoticeActions)
          ..where((row) => row.id.equals(oldId)))
        .write(GirviNoticeActionsCompanion(
            noticeText: const drift.Value(english),
            documentHash: drift.Value(_hash(english))));
    final formalId = await approve();
    for (final id in [oldId, formalId]) {
      await repository.recordNoticeDeliveryProof(
        girviId: loanId,
        noticeType: GirviNoticeType.formal,
        noticeActionId: id,
        noticeText: english,
        actionType: GirviNoticeActionTypes.noticePdfSaved,
        deliveryChannel: 'PDF File',
        deliveryStatus: 'Saved',
      );
    }
    final item = _case(loanId, clock, await history());
    expect(
        item
            .latestDeliveryProofForNotice(item.legacyNoticeActions.single)!
            .noticeActionId,
        oldId);
    expect(
        item
            .latestDeliveryProofForNotice(item.formalNoticeAction!)!
            .noticeActionId,
        formalId);
  });

  test('closed and recovering loans reject new notice approval', () async {
    await (db.update(db.girviLoans)..where((row) => row.id.equals(loanId)))
        .write(const GirviLoansCompanion(status: drift.Value('RELEASED')));
    await expectLater(approve(), throwsStateError);
    await (db.update(db.girviLoans)..where((row) => row.id.equals(loanId)))
        .write(const GirviLoansCompanion(status: drift.Value('OVERDUE')));
    await repository.recordAction(
        girviId: loanId,
        actionType: GirviNoticeActionTypes.collateralRecoveryInitiated);
    await expectLater(approve(), throwsStateError);
  });

  test('v58 upgrade preserves old notices, documents, replies and deadlines',
      () async {
    final directory =
        await Directory.systemTemp.createTemp('single_notice_v58_');
    final file = File('${directory.path}/legacy.sqlite');
    var migrationDb = AppDatabase.forTesting(NativeDatabase(file));
    final issuedAt = DateTime(2026, 9, 1, 15);
    try {
      final loan = await _seedLoan(migrationDb);
      final ids = <int>[];
      for (var stage = 1; stage <= 3; stage++) {
        final id = await _legacy(migrationDb, loan, stage, issuedAt,
            deadline: issuedAt.add(const Duration(days: 7)));
        ids.add(id);
        await migrationDb.into(migrationDb.girviNoticeDocuments).insert(
            GirviNoticeDocumentsCompanion.insert(
                girviId: loan,
                noticeActionId: id,
                noticeStage: stage,
                language: 'english',
                noticeText: 'Legacy notice $stage',
                documentHash: _hash('Legacy notice $stage')));
      }
      await GirviCustomerResponseRepository(migrationDb).record(
          girviId: loan,
          noticeActionId: ids[1],
          kind: GirviCustomerResponseKind.other,
          channel: GirviContactChannel.phoneCall,
          responseText: 'Original reply');
      await migrationDb
          .customStatement('DROP INDEX idx_girvi_one_formal_notice');
      await migrationDb.customStatement(
          'ALTER TABLE girvi_notice_actions DROP COLUMN notice_action_id');
      await migrationDb.customStatement('PRAGMA user_version = 58');
      await migrationDb.close();
      migrationDb = AppDatabase.forTesting(NativeDatabase(file));
      final saved =
          await migrationDb.select(migrationDb.girviNoticeActions).get();
      expect(saved.map((row) => row.id).toList(), ids);
      expect(saved.map((row) => row.noticeText).toList(),
          ['Legacy notice 1', 'Legacy notice 2', 'Legacy notice 3']);
      expect(
          saved.every((row) =>
              row.noticeDeadlineAt == issuedAt.add(const Duration(days: 7))),
          isTrue);
      expect(await migrationDb.select(migrationDb.girviNoticeDocuments).get(),
          hasLength(3));
      final reply =
          (await migrationDb.select(migrationDb.girviCustomerResponses).get())
              .single;
      expect(reply.noticeActionId, ids[1]);
      expect(reply.responseText, 'Original reply');
      final version =
          await migrationDb.customSelect('PRAGMA user_version').getSingle();
      expect(version.read<int>('user_version'), 60);
      final index = await migrationDb
          .customSelect(
              "SELECT name FROM sqlite_master WHERE name = 'idx_girvi_one_formal_notice'")
          .get();
      expect(index, hasLength(1));
    } finally {
      await migrationDb.close();
      await directory.delete(recursive: true);
    }
  });
}

String _hash(String text) => sha256.convert(utf8.encode(text)).toString();

Future<int> _seedLoan(AppDatabase db) async {
  final customer = await db.into(db.customers).insert(CustomersCompanion.insert(
      name: 'Workflow Customer', mobile: '0000000000'));
  return db.into(db.girviLoans).insert(GirviLoansCompanion.insert(
      ticketNo: 'GRV-SINGLE',
      customerId: customer,
      itemDescription: 'Gold ring',
      status: const drift.Value('OVERDUE')));
}

Future<int> _legacy(AppDatabase db, int loan, int stage, DateTime date,
        {DateTime? deadline}) =>
    db.into(db.girviNoticeActions).insert(GirviNoticeActionsCompanion.insert(
        girviId: loan,
        actionType: GirviNoticeHistory.preparationTypes[stage - 1],
        noticeStage: drift.Value(stage),
        noticeText: drift.Value('Legacy notice $stage'),
        documentHash: drift.Value(_hash('Legacy notice $stage')),
        actionAt: drift.Value(date),
        createdAt: drift.Value(date),
        noticeDeadlineAt: drift.Value(deadline)));

ContactRecoveryCase _case(
        int loan, DateTime now, List<GirviNoticeAction> actions,
        {List<GirviCustomerResponse> responses = const [],
        List<GirviNoticeDocumentRecord> documents = const []}) =>
    ContactRecoveryCase(
      account: GirviLoanWithCustomer(
          loan: GirviLoanModel(
              id: loan,
              ticketNo: 'GRV-SINGLE',
              customerId: 1,
              itemDescription: 'Gold ring',
              itemCount: 1,
              metalType: 'Gold',
              metalPurity: '22KT',
              grossWeight: 10,
              stoneWeight: 0,
              netWeight: 10,
              loanAmount: 10000,
              interestRate: 1,
              durationMonths: 6,
              disbursementMode: 'Cash',
              startDate: DateTime(2025, 1, 1),
              maturityDate: DateTime(2025, 7, 1),
              createdAt: DateTime(2025, 1, 1)),
          customerName: 'Workflow Customer',
          customerMobile: '0000000000'),
      noticePeriodDays: 7,
      now: now,
      actionHistory: actions,
      customerResponses: responses,
      noticeDocuments: documents,
    );
