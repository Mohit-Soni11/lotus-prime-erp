  test('old notice records do not count as a formal notice', () async {
    int? oldNoticeId;
    for (var stage = 1; stage <= 3; stage++) {
      oldNoticeId = await _legacy(
          db, loanId, stage, clock.subtract(const Duration(days: 30)));
    }
    final oldReply = GirviCustomerResponse(
      id: 1,
      girviId: loanId,
      noticeActionId: oldNoticeId,
      noticeStage: 3,
      kind: GirviCustomerResponseKind.willVisit,
      channel: GirviContactChannel.phoneCall,
      responseText: 'Old notice response',
      status: GirviPromiseStatus.open,
      receivedAt: clock.subtract(const Duration(days: 20)),
      createdAt: clock.subtract(const Duration(days: 20)),
    );
    final before = _case(loanId, clock, await history(), responses: [oldReply]);
    expect(before.noticeActions, isEmpty);
    expect(before.recoveryNoticeAction, isNull);
    expect(before.responseTimeline, isEmpty);
    expect(before.openCustomerFollowUps, isEmpty);
    expect(before.stage, ContactRecoveryStage.noticeRequired);
    expect(before.canPrepareNotice, isTrue);
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);

    final formalId = await approve();
    final after = _case(loanId, clock, await history(), responses: [oldReply]);
    expect(after.formalNoticeAction?.id, formalId);
    expect(after.noticeActions, hasLength(1));
    expect(after.responseTimeline, isEmpty);
    expect(after.stage, ContactRecoveryStage.noticePending);
    expect(await db.select(db.girviNoticeActions).get(), hasLength(4));
  });

  test('old final and unfinished recovery require a new formal notice',
      () async {
    final oldId = await _legacy(
        db, loanId, 3, clock.subtract(const Duration(days: 30)),
        deadline: clock);
    await repository.recordAction(
      girviId: loanId,
      actionType: GirviNoticeActionTypes.collateralRecoveryInitiated,
      actionAt: clock.subtract(const Duration(days: 1)),
    );
    final before = _case(loanId, clock, await history());
    expect(before.recoveryNoticeAction, isNull);
    expect(before.stage, ContactRecoveryStage.noticeRequired);
    expect(before.hasCollateralRecoveryInitiated, isFalse);
    await expectLater(
        confirmDelivery(oldId, 'Legacy notice 3'), throwsStateError);
    await expectLater(
        repository.recordCollateralRecoveryInitiated(girviId: loanId),
        throwsStateError);

    final formalId = await approve();
    await confirmDelivery(formalId, english);
    clock = clock.add(const Duration(days: 8));
    final recoveryId =
        await repository.recordCollateralRecoveryInitiated(girviId: loanId);
    final after = _case(loanId, clock, await history());
    expect(after.hasCollateralRecoveryInitiated, isTrue);
    expect(after.stage, ContactRecoveryStage.recoveryInProgress);
    final recovery = await (db.select(db.girviNoticeActions)
          ..where((row) => row.id.equals(recoveryId)))
        .getSingle();
    expect(recovery.noticeActionId, formalId);
  });

  test('old recovery does not mark the risk account as collateral recovery',
      () async {
    await _legacy(db, loanId, 3, clock.subtract(const Duration(days: 30)));
    await repository.recordAction(
      girviId: loanId,
      actionType: GirviNoticeActionTypes.collateralRecoveryInitiated,
      actionAt: clock.subtract(const Duration(days: 1)),
    );
    final riskRepository = DefaulterRepository(db: db);
    final before = await riskRepository.fetchAllDefaulters(
      syncStatuses: false,
    );
    expect(before.single.isCollateralRecovery, isFalse);
    expect(before.single.hasNoticeWorkflow, isFalse);

    final formalId = await approve();
    final withFormal = await riskRepository.fetchAllDefaulters(
      syncStatuses: false,
    );
    expect(withFormal.single.isCollateralRecovery, isFalse);
    expect(withFormal.single.hasNoticeWorkflow, isTrue);

    await confirmDelivery(formalId, english);
    clock = clock.add(const Duration(days: 8));
    await repository.recordCollateralRecoveryInitiated(girviId: loanId);
    final after = await riskRepository.fetchAllDefaulters(
      syncStatuses: false,
    );
    expect(after.single.isCollateralRecovery, isTrue);
  });

