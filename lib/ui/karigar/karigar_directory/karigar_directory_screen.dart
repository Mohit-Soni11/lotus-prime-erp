          child: ListView(
            scrollDirection: Axis.horizontal,
            children: KarigarDirectoryFilter.values.map((filter) {
              final isActive = _logic.activeFilter == filter;
              return Padding(
                padding: const EdgeInsets.only(right: 10),
                child: GestureDetector(
                  onTap: () => _logic.setFilter(filter),
                  child: AnimatedContainer(
                    duration: const Duration(milliseconds: 200),
                    padding: KarigarDirectoryStyles.chipPadding,
                    decoration: BoxDecoration(
                      color: isActive
                          ? KarigarDirectoryColors.chipActiveBg
                          : KarigarDirectoryColors.chipInactiveBg,
                      borderRadius: BorderRadius.circular(
                          KarigarDirectoryStyles.chipBorderRadius),
                      border: Border.all(
                        color: isActive
                            ? KarigarDirectoryColors.chipActive
                            : Colors.transparent,
                      ),
                    ),
                    child: Text(
                      filter.label,
                      style: isActive
                          ? KarigarDirectoryStyles.chipActiveStyle
                          : KarigarDirectoryStyles.chipInactiveStyle,
                    ),
                  ),
                ),
              );
            }).toList(),
          ),
        ),
      ]),
    );
  }

