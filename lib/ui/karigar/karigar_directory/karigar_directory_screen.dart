  Widget _buildSearchAndFilter() {
    return Container(
      padding: const EdgeInsets.fromLTRB(20, 10, 20, 8),
      child: Column(children: [
        // Search bar
        Container(
          decoration: KarigarDirectoryStyles.searchDecoration,
