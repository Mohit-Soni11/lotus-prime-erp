  Future<void> _confirmToggleStatus(
      int id, String name, bool currentlyActive) async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (_) => AlertDialog(
        backgroundColor: Colors.white,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
        title: Text(
          currentlyActive
              ? KarigarDirectoryStrings.deactivateTitle
              : 'Activate Karigar?',
          style: GoogleFonts.manrope(fontSize: 16, fontWeight: FontWeight.w700),
        ),
        content: Text(
          KarigarDirectoryStrings.deactivateBody(name),
          style: GoogleFonts.inter(fontSize: 13, color: Colors.black54),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context, false),
            child: Text(KarigarDirectoryStrings.btnCancel,
                style: GoogleFonts.inter(
                    color: Colors.black54, fontWeight: FontWeight.w600)),
          ),
          ElevatedButton(
            onPressed: () => Navigator.pop(context, true),
            style: ElevatedButton.styleFrom(
              backgroundColor: currentlyActive
                  ? KarigarDirectoryColors.danger
                  : KarigarDirectoryColors.success,
              shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(8)),
            ),
            child: Text(
              currentlyActive
                  ? KarigarDirectoryStrings.btnDeactivate
                  : KarigarDirectoryStrings.btnActivate,
              style: GoogleFonts.inter(
                  color: Colors.white, fontWeight: FontWeight.w700),
            ),
          ),
        ],
      ),
    );
    if (confirmed == true) {
      await _logic.toggleKarigarStatus(id, !currentlyActive);
    }
  }
