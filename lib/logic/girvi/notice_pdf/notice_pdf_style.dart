pw.Widget _footer(pw.Context context) {
  return pw.Row(
    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
    children: [
      pw.Text(
        'Generated by Lotus ERP',
        textDirection: pw.TextDirection.ltr,
        style: const pw.TextStyle(color: _ink, fontSize: 8.5),
      ),
      pw.Text(
        'Page ${context.pageNumber} of ${context.pagesCount}',
        textDirection: pw.TextDirection.ltr,
        style: const pw.TextStyle(color: _ink, fontSize: 8.5),
      ),
    ],
  );
}

pw.TextStyle _textStyle(
  GirviNoticeLanguage language,
  pw.Font? devanagariFont, {
  required PdfColor color,
  required double fontSize,
  bool bold = false,
  double? lineSpacing,
}) {
  return pw.TextStyle(
    color: color,
    fontSize: fontSize,
    fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
    fontFallback: devanagariFont == null ? const [] : [devanagariFont],
    lineSpacing: lineSpacing,
  );
}

String _noticeTitle(GirviNoticeType type, GirviNoticeLanguage language) =>
    language == GirviNoticeLanguage.hindi ? 'गिरवी खाता सूचना' : type.label;

String _noticeSubtitle(GirviNoticeType type, GirviNoticeLanguage language) =>
    language == GirviNoticeLanguage.hindi
        ? 'बकाया भुगतान और वसूली सूचना'
        : type.subtitle;

