import 'package:drift/drift.dart';
import 'package:lotus_erp/database/db/app_database.dart';

/// Posts only money actually received for an advance. Metal credit is excluded.
class BookingAdvanceFinancialPosting {
  const BookingAdvanceFinancialPosting(this.db);

  final AppDatabase db;

  Future<void> post({
    required int receiptId,
    required String orderNo,
    required String customerName,
    required DateTime date,
    required double cash,
    required double upi,
    required double card,
  }) async {
    final bankAccountId =
        (upi > 0 || card > 0) ? await _preferredBankAccountId() : null;
    if ((upi > 0 || card > 0) && bankAccountId == null) {
      throw StateError(
        'Add an active bank account before recording a UPI or card advance.',
      );
    }
    final reference = '$orderNo#ADV#$receiptId';
    if (cash > 0) {
      await db.into(db.cashTransactions).insert(
            CashTransactionsCompanion.insert(
              txnId: 'BOOK-ADV-$receiptId-CASH',
              txnDate: date,
              type: 'INCOME',
              category: 'ADVANCE',
              amount: Value(cash),
              paymentMode: const Value('CASH'),
              description: Value('Advance received for $orderNo'),
              referenceId: Value(reference),
              referenceType: const Value('ORDER'),
              partyName: Value(customerName),
              isAutoGenerated: const Value(true),
            ),
          );
    }
    for (final (mode, amount) in [('UPI', upi), ('CARD', card)]) {
      if (amount <= 0) continue;
      await db.into(db.bankTransactions).insert(
            BankTransactionsCompanion.insert(
              txnId: 'BOOK-ADV-$receiptId-$mode',
              accountId: bankAccountId!,
              txnDate: date,
              type: 'CREDIT',
              category: 'ADVANCE_RECEIVED',
              amount: Value(amount),
              paymentMode: Value(mode),
              description: Value('Advance received for $orderNo'),
              referenceId: Value(reference),
              referenceType: const Value('ORDER'),
              partyName: Value(customerName),
              isAutoGenerated: const Value(true),
            ),
          );
    }
  }

  Future<int?> _preferredBankAccountId() async {
    final account = await (db.select(db.bankAccounts)
          ..where((row) => row.isActive.equals(true))
          ..orderBy([
            (row) => OrderingTerm.desc(row.isPrimary),
            (row) => OrderingTerm.asc(row.id),
          ])
          ..limit(1))
        .getSingleOrNull();
    return account?.id;
  }
}
