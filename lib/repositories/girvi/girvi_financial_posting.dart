import 'package:drift/drift.dart' as drift;

import 'package:lotus_erp/database/db/app_database.dart';
import '../../models/girvi/girvi_persistence_models.dart';

/// Writes the cash/bank side of a Girvi event inside the caller's transaction.
class GirviFinancialPosting {
  const GirviFinancialPosting(this.db);

  final AppDatabase db;

  Future<void> disbursement({
    required int loanId,
    required String ticketNo,
    required String customerName,
    required DateTime date,
    required GirviDisbursementInput input,
  }) async {
    await _post(
      transactionId: 'GIRVI-DISB-$loanId-${input.sequenceNo}',
      date: date,
      mode: input.mode,
      amount: input.amount,
      bankAccountId: input.bankAccountId,
      cashType: 'EXPENSE',
      bankType: 'DEBIT',
      cashCategory: 'GIRVI_GIVEN',
      bankCategory: 'GIRVI_GIVEN',
      description: 'Pledge advance for $ticketNo',
      referenceId: 'GIRVI-$loanId',
      customerName: customerName,
    );
  }

  Future<void> collection({
    required int loanId,
    required int paymentId,
    required String customerName,
    required DateTime date,
    required String mode,
    required double principal,
    required double interest,
    int? bankAccountId,
  }) async {
    if (principal > 0) {
      await _post(
        transactionId: 'GIRVI-PAY-$paymentId-P',
        date: date,
        mode: mode,
        amount: principal,
        bankAccountId: bankAccountId,
        cashType: 'INCOME',
        bankType: 'CREDIT',
        cashCategory: 'GIRVI_RETURN',
        bankCategory: 'DUE_COLLECTION',
        description: 'Pledge principal collected',
        referenceId: 'GIRVI-$loanId-PAY-$paymentId',
        customerName: customerName,
      );
    }
    if (interest > 0) {
      await _post(
        transactionId: 'GIRVI-PAY-$paymentId-I',
        date: date,
        mode: mode,
        amount: interest,
        bankAccountId: bankAccountId,
        cashType: 'INCOME',
        bankType: 'CREDIT',
        cashCategory: 'INTEREST_RECEIVED',
        bankCategory: 'INTEREST_RECEIVED',
        description: 'Pledge interest collected',
        referenceId: 'GIRVI-$loanId-PAY-$paymentId',
        customerName: customerName,
      );
    }
  }

  Future<void> _post({
    required String transactionId,
    required DateTime date,
    required String mode,
    required double amount,
    required int? bankAccountId,
    required String cashType,
    required String bankType,
    required String cashCategory,
    required String bankCategory,
    required String description,
    required String referenceId,
    required String customerName,
  }) async {
    if (amount <= 0) return;
    final normalizedMode = mode.trim().toUpperCase();
    if (normalizedMode == 'CASH') {
      await db.into(db.cashTransactions).insert(
            CashTransactionsCompanion.insert(
              txnId: transactionId,
              txnDate: date,
              type: cashType,
              category: cashCategory,
              amount: drift.Value(amount),
              paymentMode: const drift.Value('CASH'),
              description: drift.Value(description),
              referenceId: drift.Value(referenceId),
              referenceType: const drift.Value('GIRVI'),
              partyName: drift.Value(customerName),
              isAutoGenerated: const drift.Value(true),
            ),
          );
      return;
    }

    final activeAccounts = (await db.select(db.bankAccounts).get())
        .where((account) => account.isActive)
        .toList(growable: false);
    final selected = bankAccountId == null
        ? activeAccounts.length == 1
            ? activeAccounts.single
            : null
        : activeAccounts
            .where((account) => account.id == bankAccountId)
            .firstOrNull;
    if (selected == null) {
      throw StateError(
          'Select an active bank account for non-cash Girvi payment.');
    }
    final paymentMode = switch (normalizedMode) {
      'BANK TRANSFER' => 'NEFT',
      'NEFT' => 'NEFT',
      'CHEQUE' => 'CHEQUE',
      'UPI' => 'UPI',
      _ => throw ArgumentError.value(
          mode, 'mode', 'Unsupported Girvi payment mode'),
    };
    await db.into(db.bankTransactions).insert(
          BankTransactionsCompanion.insert(
            txnId: transactionId,
            accountId: selected.id,
            txnDate: date,
            type: bankType,
            category: bankCategory,
            amount: drift.Value(amount),
            paymentMode: drift.Value(paymentMode),
            description: drift.Value(description),
            referenceId: drift.Value(referenceId),
            referenceType: const drift.Value('GIRVI'),
            partyName: drift.Value(customerName),
            isAutoGenerated: const drift.Value(true),
          ),
        );
  }
}
