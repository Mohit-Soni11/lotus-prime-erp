import 'girvi_notice_account_guard.dart';

class GirviNoticeActionRepository {
  GirviNoticeActionRepository(this._db, {DateTime Function()? now})
      : _now = now ?? DateTime.now;

  final DateTime Function() _now;

  final AppDatabase _db;
  late final GirviNoticeAccountGuard _accountGuard =
      GirviNoticeAccountGuard(_db);
  bool _schemaReady = false;

  Future<void> ensureSchema() async {
    if (_schemaReady) return;
    await _db.ensureGirviNoticeActionSchema();
    await _db.ensureGirviNoticeDocumentSchema();
    _schemaReady = true;
  }

  Future<int> recordNoticeDraft({
    required int girviId,
    required String noticeText,
    String performedBy = 'LOCAL_OPERATOR',
  }) {
    return recordAction(
      girviId: girviId,
      actionType: GirviNoticeActionTypes.noticeDraftCopied,
      noticeText: noticeText,
      documentHash: _documentHash(noticeText),
      performedBy: performedBy,
      actionNote: 'Legal notice draft copied for customer communication.',
    );
  }

  Future<int> recordNoticePrepared({
    required int girviId,
    required GirviNoticeType noticeType,
    required String noticeText,
    required int noticePeriodDays,
    String? autoGeneratedText,
    Map<GirviNoticeLanguage, String>? noticeDocuments,
    Map<GirviNoticeLanguage, String>? autoGeneratedDocuments,
    GirviNoticeLanguage primaryLanguage = GirviNoticeLanguage.english,
    int? supersedesNoticeActionId,
    String performedBy = 'LOCAL_OPERATOR',
  }) async {
    final generated = _normalizeText(autoGeneratedText);
    final finalText = _normalizeText(noticeText);
    if (finalText == null) {
      throw ArgumentError.value(
          noticeText, 'noticeText', 'Notice text is required.');
    }
    final edited = generated != null && generated != finalText;
    final localizedDocuments = _normalizeDocuments(noticeDocuments);
    final localizedGenerated = _normalizeDocuments(autoGeneratedDocuments);
    if (noticeDocuments != null &&
        !localizedDocuments.containsKey(GirviNoticeLanguage.english)) {
      throw ArgumentError.value(
        noticeDocuments,
        'noticeDocuments',
        'An approved English notice document is required.',
      );
    }
    final waitDays = noticePeriodDays <= 0 ? 7 : noticePeriodDays;
    if (noticeDocuments != null &&
        localizedDocuments[primaryLanguage] != finalText) {
      throw ArgumentError(
          'The primary text must match its approved language version.');
    }
    await ensureSchema();

    return _db.transaction(() async {
      await _accountGuard.requireOutstanding(
        girviId,
        _now(),
        requireMaturity: true,
      );
      final existing = await _recoveryNotice(girviId);
      final recovery = await (_db.select(_db.girviNoticeActions)
            ..where((row) =>
                row.girviId.equals(girviId) &
                row.actionType.isIn(const [
                  GirviNoticeActionTypes.collateralRecoveryInitiated,
                  GirviNoticeActionTypes.disposalSettled,
                ]) &
                (existing == null
                    ? row.actionType
                        .equals(GirviNoticeActionTypes.disposalSettled)
                    : row.actionType
                            .equals(GirviNoticeActionTypes.disposalSettled) |
                        row.noticeActionId.equals(existing.id) |
                        (row.noticeActionId.isNull() &
                            row.actionAt
                                .isBiggerOrEqualValue(existing.actionAt))))
            ..limit(1))
          .getSingleOrNull();
      if (recovery != null) {
        throw StateError(
            'A notice cannot be prepared after recovery has started.');
      }
      final approvedEnglish = existing == null
          ? null
          : await (_db.select(_db.girviNoticeDocuments)
                ..where((row) =>
                    row.noticeActionId.equals(existing.id) &
                    row.language.equals(GirviNoticeLanguage.english.fileLabel))
                ..limit(1))
              .getSingleOrNull();
      final correctsSimpleFormal =
          existing?.actionType == GirviNoticeActionTypes.noticePrepared &&
              supersedesNoticeActionId == existing?.id &&
              noticeType == GirviNoticeType.formal &&
              (approvedEnglish?.noticeText ?? existing?.noticeText ?? '')
                  .contains('Simple Interest Breakdown') &&
              finalText.contains('Compound Interest Breakdown');
      if (existing != null && !correctsSimpleFormal) {
        throw StateError('${noticeType.label} has already been saved.');
      }
      if (existing == null && supersedesNoticeActionId != null) {
        throw StateError('The notice to correct is no longer current.');
      }

      final now = _now();
      final actionId = await recordAction(
        girviId: girviId,
        actionType: noticeType.actionType,
        noticeActionId: supersedesNoticeActionId,
        noticeStage: noticeType.stage,
        noticeText: finalText,
        documentHash: _documentHash(finalText),
        performedBy: performedBy,
        approvedBy: performedBy,
        approvedAt: now,
        noticeDeadlineAt: now.add(Duration(days: waitDays)),
        actionAt: now,
        actionNote: [
          '${noticeType.label} approved for customer communication.',
          if (supersedesNoticeActionId != null)
            'Corrects approved notice action $supersedesNoticeActionId; the original remains in the audit record.',
          edited
              ? 'Final version was manually edited before approval.'
              : 'Approved version matches the generated notice.',
          if (edited) 'Original generated notice: $generated',
          if (localizedDocuments.isNotEmpty)
            'Approved language versions: ${localizedDocuments.keys.map((language) => language.label).join(', ')}.',
        ].join('\n'),
      );
      for (final entry in localizedDocuments.entries) {
        final sourceText = localizedGenerated[entry.key];
        await _db.into(_db.girviNoticeDocuments).insert(
              GirviNoticeDocumentsCompanion.insert(
                girviId: girviId,
                noticeActionId: actionId,
                noticeStage: noticeType.stage,
                language: entry.key.fileLabel,
                noticeText: entry.value,
                documentHash: _documentHash(entry.value),
                generatedText: Value(sourceText),
                wasManuallyEdited: Value(
                  sourceText != null && sourceText != entry.value,
                ),
                approvedBy: Value(performedBy),
                approvedAt: Value(now),
                createdAt: Value(now),
              ),
            );
      }
      return actionId;
    });
  }

  Future<int> recordCollateralRecoveryInitiated({
    required int girviId,
    String? note,
    int noticePeriodDays = 7,
    String performedBy = 'LOCAL_OPERATOR',
  }) async {
    await ensureSchema();
    return _db.transaction(() async {
      await _accountGuard.requireOutstanding(girviId, _now());
      final approvedNotice = await _recoveryNotice(girviId);
      if (approvedNotice == null) {
        throw StateError(
            'An approved formal notice is required before recovery.');
      }
      final confirmedDeliveries = await (_db.select(_db.girviNoticeActions)
            ..where((action) =>
                action.girviId.equals(girviId) &
                action.noticeActionId.equals(approvedNotice.id) &
                action.actionType.equals(
                  GirviNoticeActionTypes.noticeDeliveryRecorded,
                )))
          .get();
      if (confirmedDeliveries.isEmpty) {
        throw StateError('Record confirmed customer delivery before recovery.');
      }
      final firstDelivery = confirmedDeliveries
          .map((action) => action.deliveredAt ?? action.actionAt)
          .reduce((first, date) => date.isBefore(first) ? date : first);
      final recoveryEligibleAt = GirviNoticeReviewPeriod.deadline(
        approvedAt: approvedNotice.actionAt,
        approvedDeadline: approvedNotice.noticeDeadlineAt,
        deliveredAt: firstDelivery,
        fallbackDays: noticePeriodDays,
      )!;
      if (_now().isBefore(recoveryEligibleAt)) {
        throw StateError('The notice review period has not completed.');
      }
      final existing = await (_db.select(_db.girviNoticeActions)
            ..where(
              (action) =>
                  action.girviId.equals(girviId) &
                  action.actionType.equals(
                    GirviNoticeActionTypes.collateralRecoveryInitiated,
                  ) &
                  (action.noticeActionId.equals(approvedNotice.id) |
                      (action.noticeActionId.isNull() &
                          action.actionAt
                              .isBiggerOrEqualValue(approvedNotice.actionAt))),
            )
            ..limit(1))
          .getSingleOrNull();
      if (existing != null) {
        throw StateError('Collateral recovery has already been initiated.');
      }
      return recordAction(
        girviId: girviId,
        actionType: GirviNoticeActionTypes.collateralRecoveryInitiated,
        noticeActionId: approvedNotice.id,
        performedBy: performedBy,
        actionNote: note ??
            'Collateral moved to recovery after completion of the notice workflow.',
      );
    });
  }

  Future<int> recordDisposalSettlement({
    required int girviId,
    required double pledgedValuation,
    required double recoveredAmount,
    required double penaltyAmount,
    required double settlementTotal,
    required double customerBalanceDue,
    required double customerSurplus,
    String? note,
    String performedBy = 'LOCAL_OPERATOR',
  }) async {
    await ensureSchema();
    return _db.transaction(() async {
      final approvedNotice = await _recoveryNotice(girviId);
      if (approvedNotice == null) {
        throw StateError(
            'An approved formal notice is required before settlement.');
      }
      final recoveryStarted = await (_db.select(_db.girviNoticeActions)
            ..where(
              (action) =>
                  action.girviId.equals(girviId) &
                  action.actionType.equals(
                    GirviNoticeActionTypes.collateralRecoveryInitiated,
                  ) &
                  (action.noticeActionId.equals(approvedNotice.id) |
                      (action.noticeActionId.isNull() &
                          action.actionAt
                              .isBiggerOrEqualValue(approvedNotice.actionAt))),
            )
            ..limit(1))
          .getSingleOrNull();
      if (recoveryStarted == null) {
        throw StateError('Collateral recovery must start before settlement.');
      }
      final alreadySettled = await (_db.select(_db.girviNoticeActions)
            ..where(
              (action) =>
                  action.girviId.equals(girviId) &
                  action.actionType
                      .equals(GirviNoticeActionTypes.disposalSettled),
            )
            ..limit(1))
          .getSingleOrNull();
      if (alreadySettled != null) {
        throw StateError('Recovery settlement is already closed.');
      }
      return recordAction(
        girviId: girviId,
        actionType: GirviNoticeActionTypes.disposalSettled,
        noticeActionId: approvedNotice.id,
        performedBy: performedBy,
        actionNote: note ?? 'Recovery settlement closed after notice review.',
        pledgedValuation: pledgedValuation,
        recoveredAmount: recoveredAmount,
        penaltyAmount: penaltyAmount,
        settlementTotal: settlementTotal,
        customerBalanceDue: customerBalanceDue,
        customerSurplus: customerSurplus,
      );
    });
  }

  Future<int> recordNoticeDeliveryProof({
    required int girviId,
    required GirviNoticeType noticeType,
    required String noticeText,
    required String actionType,
    required String deliveryChannel,
    required String deliveryStatus,
    GirviNoticeLanguage? noticeLanguage,
    int? noticeActionId,
    String? deliveryReference,
    DateTime? deliveredAt,
    String performedBy = 'LOCAL_OPERATOR',
  }) async {
    if (actionType == GirviNoticeActionTypes.noticeDeliveryRecorded &&
        (deliveryStatus.trim() != 'Delivered' ||
            (deliveryReference?.trim().isNotEmpty != true))) {
      throw ArgumentError(
        'Confirmed delivery requires a delivered status and evidence reference.',
      );
    }
    await ensureSchema();
    return _db.transaction(() async {
      final prepared =
          await _approvedNotice(girviId, noticeActionId: noticeActionId);
      final finalText = _normalizeText(noticeText);
      if (prepared == null || finalText == null) {
        throw StateError('Save the approved notice before recording delivery.');
      }
      final localizedHash = await _approvedDocumentHash(
        noticeActionId: prepared.id,
        language: noticeLanguage,
      );
      if (noticeLanguage != null && localizedHash == null) {
        final legacyLanguage =
            RegExp(r'[\u0900-\u097F]').hasMatch(prepared.noticeText ?? '')
                ? GirviNoticeLanguage.hindi
                : GirviNoticeLanguage.english;
        if (noticeLanguage != legacyLanguage) {
          throw StateError(
              'This language was not saved for the approved notice.');
        }
      }
      final approvedDocumentHash = localizedHash ?? prepared.documentHash;
      if (approvedDocumentHash != _documentHash(finalText)) {
        throw StateError(
            'Delivery proof must use the saved, approved notice version.');
      }
      final deliveryDate = deliveredAt ?? _now();
      if (actionType == GirviNoticeActionTypes.noticeDeliveryRecorded &&
          (deliveryDate.isBefore(prepared.actionAt) ||
              deliveryDate.isAfter(_now()))) {
        throw StateError(
            'Delivery date must follow notice approval and cannot be in the future.');
      }
      return recordAction(
        girviId: girviId,
        actionType: actionType,
        noticeActionId: prepared.id,
        noticeStage: prepared.noticeStage ?? 1,
        noticeText: finalText,
        documentHash: approvedDocumentHash,
        performedBy: performedBy,
        actionNote:
            '${noticeType.label}${noticeLanguage == null ? '' : ' (${noticeLanguage.label})'} $deliveryStatus through $deliveryChannel.',
        deliveryChannel: deliveryChannel,
        deliveryStatus: deliveryStatus,
        deliveryReference: deliveryReference,
        deliveredAt: actionType == GirviNoticeActionTypes.noticeDeliveryRecorded
            ? deliveryDate
            : null,
      );
    });
  }

  Future<int> recordAction({
    required int girviId,
    required String actionType,
    int? noticeActionId,
    int? noticeStage,
    String? noticeText,
    String? documentHash,
    String? actionNote,
    String? performedBy,
    String? approvedBy,
    DateTime? approvedAt,
    DateTime? noticeDeadlineAt,
    DateTime? actionAt,
    double pledgedValuation = 0,
    double recoveredAmount = 0,
    double penaltyAmount = 0,
    double settlementTotal = 0,
    double customerBalanceDue = 0,
    double customerSurplus = 0,
    String? deliveryChannel,
    String? deliveryStatus,
    String? deliveryReference,
    DateTime? deliveredAt,
  }) async {
    if (!GirviNoticeActionTypes.recordableTypes.contains(actionType)) {
      throw StateError('Unknown notice action type.');
    }
    await ensureSchema();
    final now = actionAt ?? _now();
    return _db.into(_db.girviNoticeActions).insert(
          GirviNoticeActionsCompanion.insert(
            girviId: girviId,
            actionType: actionType,
            noticeActionId: Value(noticeActionId),
            createdAt: Value(now),
            actionAt: Value(now),
            noticeStage: Value(noticeStage),
            noticeText: Value(_normalizeText(noticeText)),
            documentHash: Value(_normalizeText(documentHash)),
            actionNote: Value(_normalizeText(actionNote)),
            performedBy: Value(_normalizeText(performedBy)),
            approvedBy: Value(_normalizeText(approvedBy)),
            approvedAt: Value(approvedAt),
            noticeDeadlineAt: Value(noticeDeadlineAt),
            pledgedValuation: Value(pledgedValuation),
            recoveredAmount: Value(recoveredAmount),
            penaltyAmount: Value(penaltyAmount),
            settlementTotal: Value(settlementTotal),
            customerBalanceDue: Value(customerBalanceDue),
            customerSurplus: Value(customerSurplus),
            deliveryChannel: Value(_normalizeText(deliveryChannel)),
            deliveryStatus: Value(_normalizeText(deliveryStatus)),
            deliveryReference: Value(_normalizeText(deliveryReference)),
            deliveredAt: Value(deliveredAt),
          ),
        );
  }

  Future<Map<int, GirviNoticeAction>> latestByGirviIds(
    List<int> girviIds,
  ) async {
    await ensureSchema();
    if (girviIds.isEmpty) return {};

    final rows = await (_db.select(_db.girviNoticeActions)
          ..where((row) => row.girviId.isIn(girviIds))
          ..orderBy([
            (row) => OrderingTerm.desc(row.actionAt),
            (row) => OrderingTerm.desc(row.id),
          ]))
        .get();

    final result = <int, GirviNoticeAction>{};
    for (final row in rows) {
      final action = _mapData(row);
      result[action.girviId] ??= action;
    }
    return result;
  }

  Future<Map<int, List<GirviNoticeAction>>> actionsByGirviIds(
    List<int> girviIds,
  ) async {
    await ensureSchema();
    if (girviIds.isEmpty) return {};

    final rows = await (_db.select(_db.girviNoticeActions)
          ..where((row) => row.girviId.isIn(girviIds))
          ..orderBy([
            (row) => OrderingTerm.desc(row.actionAt),
            (row) => OrderingTerm.desc(row.id),
          ]))
        .get();

    final result = <int, List<GirviNoticeAction>>{};
    for (final row in rows) {
      final action = _mapData(row);
      result.putIfAbsent(action.girviId, () => []).add(action);
    }
    return result;
  }

  GirviNoticeAction _mapData(GirviNoticeActionData row) {
    return GirviNoticeAction(
      id: row.id,
      girviId: row.girviId,
      actionType: row.actionType,
      noticeActionId: row.noticeActionId,
      noticeStage: row.noticeStage,
      noticeText: _normalizeText(row.noticeText),
      documentHash: _normalizeText(row.documentHash),
      actionNote: _normalizeText(row.actionNote),
      performedBy: _normalizeText(row.performedBy),
      approvedBy: _normalizeText(row.approvedBy),
      approvedAt: row.approvedAt,
      noticeDeadlineAt: row.noticeDeadlineAt,
      pledgedValuation: row.pledgedValuation,
      recoveredAmount: row.recoveredAmount,
      penaltyAmount: row.penaltyAmount,
      settlementTotal: row.settlementTotal,
      customerBalanceDue: row.customerBalanceDue,
      customerSurplus: row.customerSurplus,
      deliveryChannel: _normalizeText(row.deliveryChannel),
      deliveryStatus: _normalizeText(row.deliveryStatus),
      deliveryReference: _normalizeText(row.deliveryReference),
      deliveredAt: row.deliveredAt,
      actionAt: row.actionAt,
      createdAt: row.createdAt,
      updatedAt: row.updatedAt,
    );
  }

  Future<GirviNoticeActionData?> _recoveryNotice(int girviId) async {
    return (_db.select(_db.girviNoticeActions)
          ..where((row) =>
              row.girviId.equals(girviId) &
              row.actionType.equals(GirviNoticeActionTypes.noticePrepared))
          ..orderBy([
            (row) => OrderingTerm.desc(row.actionAt),
            (row) => OrderingTerm.desc(row.id)
          ])
          ..limit(1))
        .getSingleOrNull();
  }

  Future<GirviNoticeActionData?> _approvedNotice(int girviId,
      {int? noticeActionId}) {
    final query = _db.select(_db.girviNoticeActions)
      ..where((row) =>
          row.girviId.equals(girviId) &
          row.actionType.isIn(GirviNoticeActionTypes.preparationTypes));
    if (noticeActionId != null) {
      query.where((row) => row.id.equals(noticeActionId));
    } else {
      query.where((row) =>
          row.actionType.equals(GirviNoticeActionTypes.noticePrepared));
    }
    return (query
          ..orderBy([
            (row) => OrderingTerm.desc(row.actionAt),
            (row) => OrderingTerm.desc(row.id)
          ])
          ..limit(1))
        .getSingleOrNull();
  }

  Future<String?> _approvedDocumentHash({
    required int noticeActionId,
    required GirviNoticeLanguage? language,
  }) async {
    if (language == null) return null;
    final document = await (_db.select(_db.girviNoticeDocuments)
          ..where(
            (row) =>
                row.noticeActionId.equals(noticeActionId) &
                row.language.equals(language.fileLabel),
          )
          ..limit(1))
        .getSingleOrNull();
    return document?.documentHash;
  }

  Map<GirviNoticeLanguage, String> _normalizeDocuments(
    Map<GirviNoticeLanguage, String>? documents,
  ) {
    if (documents == null) return const {};
    final result = <GirviNoticeLanguage, String>{};
    for (final entry in documents.entries) {
      final text = _normalizeText(entry.value);
      if (text != null) result[entry.key] = text;
    }
    return result;
  }

  String? _normalizeText(Object? value) {
    final text = value?.toString().trim();
    if (text == null || text.isEmpty) return null;
    return text;
  }

  String _documentHash(String value) =>
      sha256.convert(utf8.encode(value.trim())).toString();
}
