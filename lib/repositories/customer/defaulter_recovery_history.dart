part of 'defaulter_repository.dart';

DefaulterModel _mapRecoveredAccount({
  required GirviLoan loan,
  required Customer customer,
  required _PaymentSummary summary,
  required _PledgedItemSnapshot itemSnapshot,
  required GirviNoticeActionData settlement,
  required String address,
}) {
  final city = customer.city?.trim();
  return DefaulterModel(
    loanId: loan.id,
    customerId: customer.id,
    customerName: customer.name,
    mobile: CustomerContactValue.displayMobile(customer.mobile),
    city: city == null || city.isEmpty ? 'Not specified' : city,
    address: address,
    customerType: customer.customerTier,
    defaulterType: DefaulterType.loan,
    referenceNo: loan.ticketNo,
    itemSummary: itemSnapshot.summary,
    pledgedItemCount: itemSnapshot.itemCount,
    itemName: itemSnapshot.itemName,
    metalType: itemSnapshot.metalType,
    purity: itemSnapshot.purity,
    pieces: itemSnapshot.pieces,
    grossWeight: itemSnapshot.grossWeight,
    lessWeight: itemSnapshot.lessWeight,
    statusLabel: 'Recovery Closed',
    statusValue: loan.status,
    principalAmount: loan.loanAmount + summary.legacyPrincipalRepaid,
    principalOutstanding: 0,
    interestRate: loan.interestRate,
    interestAccrued: 0,
    interestOutstanding: 0,
    totalDue: 0,
    totalReceived: summary.totalReceived,
    currentMonthReceived: 0,
    netWeight:
        itemSnapshot.netWeight > 0 ? itemSnapshot.netWeight : loan.netWeight,
    startDate: loan.startDate,
    maturityDate: loan.maturityDate,
    lastPaymentDate: summary.lastPaymentDate,
    lastActivityAt: settlement.actionAt,
    daysOverdue: 0,
    monthsOverdue: 0,
    unpaidInterestMonths: 0,
    maturityOverdueDays: 0,
    isInterestOverdue: false,
    isMaturityOverdue: false,
    hasInterestPaidBeforeMaturity: false,
    isCollateralRecovery: true,
    isRecoverySettled: true,
    recoveredAmount: settlement.recoveredAmount,
    recoverySettlementTotal: settlement.settlementTotal,
    recoveryBalanceDue: settlement.customerBalanceDue,
    recoverySurplus: settlement.customerSurplus,
    recoverySettledAt: settlement.actionAt,
    hasNoticeWorkflow: true,
    riskLevel: DefaulterRiskLevel.low,
    collectionStage: 'Recovery Closed',
    nextActionLabel: 'View recovery record',
  );
}
