import 'package:drift/drift.dart';

import '../../database/db/app_database.dart';
import '../../models/finance/cash_book/cash_book_enums.dart';
import '../../models/reports/day_book/day_book_expense_record.dart';

/// Reads Expense Entry's saved source transactions without creating postings.
class DayBookExpenseRepository {
  const DayBookExpenseRepository(this._db);

  final AppDatabase _db;

  Future<List<DayBookExpenseRecord>> fetch(DateTime date) async {
    final start = DateTime(date.year, date.month, date.day);
    final end = DateTime(date.year, date.month, date.day + 1);
    final rows = await (_db.select(_db.cashTransactions)
          ..where((row) =>
              row.type.equals(CashTransactionType.expense.dbValue) &
              row.isVoided.equals(false) &
              row.isAutoGenerated.equals(false) &
              row.txnDate.isBiggerOrEqualValue(start) &
              row.txnDate.isSmallerThanValue(end))
          ..orderBy([(row) => OrderingTerm.asc(row.txnDate)]))
        .get();
    return List.unmodifiable(rows.where((row) {
      // Purchase payments and Girvi disbursements have their own cards.
      return row.category != ExpenseCategory.purchasePayment.dbValue &&
          row.category != ExpenseCategory.girviGiven.dbValue;
    }).map((row) => DayBookExpenseRecord(
          reference: row.txnId,
          category: _categoryLabel(row.category, row.customLabel),
          amount: row.amount,
          paymentMode: row.paymentMode,
          description: row.description,
          partyName: row.partyName,
        )));
  }

  static String _categoryLabel(String category, String? customLabel) {
    if (customLabel != null && customLabel.trim().isNotEmpty) {
      return customLabel.trim();
    }
    if (ExpenseCategory.values.any((item) => item.dbValue == category)) {
      return resolveDisplayLabel(
        type: CashTransactionType.expense,
        categoryDbValue: category,
      );
    }
    final words =
        category.toLowerCase().split('_').where((part) => part.isNotEmpty);
    return words
        .map((part) => '${part[0].toUpperCase()}${part.substring(1)}')
        .join(' ');
  }
}
