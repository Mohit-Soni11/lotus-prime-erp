import 'package:drift/drift.dart';

import '../../core/logging/app_logger.dart';
import '../../database/db/app_database.dart';
import '../../features/finance/ledger/data/finance_day_closure_repository.dart';
import '../../features/finance/transactions/domain/services/finance_transaction_numbering.dart';
import '../../models/finance/bank_book/bank_book_enums.dart' as bank;
import '../../models/finance/cash_book/cash_book_enums.dart';

class ManualIncomeBankAccount {
  const ManualIncomeBankAccount(this.id, this.label);

  final int id;
  final String label;
}

class DayBookManualIncomeRepository {
  const DayBookManualIncomeRepository(this._db);

  final AppDatabase _db;

  Future<List<ManualIncomeBankAccount>> listActiveBankAccounts() async {
    final accounts = await (_db.select(_db.bankAccounts)
          ..where((account) => account.isActive.equals(true)))
        .get();
    accounts.sort((a, b) => a.accountName.compareTo(b.accountName));
    return List.unmodifiable(accounts.map((account) => ManualIncomeBankAccount(
          account.id,
          '${account.accountName} · ${account.bankName}',
        )));
  }

  Future<bool> save({
    required IncomeCategory category,
    required double amount,
    required PaymentMode paymentMode,
    required DateTime date,
    int? bankAccountId,
    String? customLabel,
  }) async {
    final label = customLabel?.trim();
    if (!category.isManualDayBookIncome ||
        !amount.isFinite ||
        amount <= 0 ||
        (amount * 100 - (amount * 100).round()).abs() > 0.000001 ||
        (category.requiresCustomLabel && (label == null || label.isEmpty)) ||
        !const {PaymentMode.cash, PaymentMode.bank}.contains(paymentMode) ||
        (paymentMode == PaymentMode.bank && bankAccountId == null)) {
      return false;
    }

    try {
      await _db.transaction(() async {
        if (await FinanceDayClosureRepository(_db).isClosed(date)) {
          throw StateError('The selected Day Book date is closed.');
        }
        final description =
            category.requiresCustomLabel ? label! : category.displayLabel;
        final numbering = FinanceTransactionNumbering(_db);
        if (paymentMode == PaymentMode.cash) {
          final transactionId = await numbering.nextCashTransactionId();
          await _db.into(_db.cashTransactions).insert(
                CashTransactionsCompanion.insert(
                  txnId: transactionId,
                  txnDate: date,
                  type: CashTransactionType.income.dbValue,
                  category: category.dbValue,
                  amount: Value(amount),
                  paymentMode: Value(PaymentMode.cash.dbValue),
                  customLabel: Value(label),
                  description: Value(description),
                  referenceId: Value(transactionId),
                  referenceType: const Value('MANUAL_INCOME'),
                  isAutoGenerated: const Value(false),
                ),
              );
          return;
        }

        final account = await (_db.select(_db.bankAccounts)
              ..where((row) =>
                  row.id.equals(bankAccountId!) & row.isActive.equals(true)))
            .getSingleOrNull();
        if (account == null) throw StateError('Choose an active bank account.');
        final transactionId = await numbering.nextBankTransactionId();
        await _db.into(_db.bankTransactions).insert(
              BankTransactionsCompanion.insert(
                txnId: transactionId,
                accountId: Value(account.id),
                txnDate: date,
                type: bank.BankTransactionType.credit.dbValue,
                category: category.dbValue,
                amount: Value(amount),
                paymentMode: Value(bank.BankPaymentMode.bankTransfer.dbValue),
                description: Value(description),
                referenceId: Value(transactionId),
                referenceType: const Value('MANUAL_INCOME'),
                isAutoGenerated: const Value(false),
              ),
            );
      });
      return true;
    } catch (error, stackTrace) {
      AppLogger.error('Day Book manual income could not be saved.',
          error: error, stackTrace: stackTrace);
      return false;
    }
  }
}
