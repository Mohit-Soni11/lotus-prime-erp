import 'package:drift/drift.dart';

import '../../database/db/app_database.dart';
import '../../features/finance/transactions/domain/services/finance_transaction_numbering.dart';
import '../../models/finance/cash_book/cash_book_enums.dart';

/// Writes the physical-count adjustment into the same source used by Expense
/// Entry. Bank rows are paired with a noncash source row for that screen.
class DayBookBalanceAdjustmentPosting {
  const DayBookBalanceAdjustmentPosting(this.db);

  final AppDatabase db;

  Future<String?> postShortage({
    required DateTime date,
    required String dayKey,
    required double cashAmount,
    required double bankAmount,
    required ExpenseCategory category,
    required String note,
    int? bankAccountId,
  }) async {
    String? firstId;
    if (cashAmount >= 0.01) {
      firstId = await _postExpense(
        date: date,
        dayKey: dayKey,
        amount: cashAmount,
        category: category,
        note: note,
        isBank: false,
      );
    }
    if (bankAmount >= 0.01) {
      if (bankAccountId == null) {
        throw StateError(
            'Select a bank account before posting a bank expense.');
      }
      final bankSourceId = await _postExpense(
        date: date,
        dayKey: dayKey,
        amount: bankAmount,
        category: category,
        note: note,
        isBank: true,
        bankAccountId: bankAccountId,
      );
      firstId ??= bankSourceId;
    }
    return firstId;
  }

  Future<String> _postExpense({
    required DateTime date,
    required String dayKey,
    required double amount,
    required ExpenseCategory category,
    required String note,
    required bool isBank,
    int? bankAccountId,
  }) async {
    final numbering = FinanceTransactionNumbering(db);
    final sourceId = await numbering.nextExpenseTransactionId();
    await db.into(db.cashTransactions).insert(
          CashTransactionsCompanion.insert(
            txnId: sourceId,
            txnDate: date,
            type: CashTransactionType.expense.dbValue,
            category: category.dbValue,
            amount: Value(amount),
            paymentMode: Value(isBank ? 'BANK' : 'CASH'),
            description: Value(note),
            referenceId: Value('DAYBAL-$dayKey'),
            referenceType: const Value('DAY_BOOK_BALANCE'),
            isAutoGenerated: const Value(true),
            isVoided: const Value(false),
          ),
        );
    if (isBank) {
      final bankId = await numbering.nextBankTransactionId();
      await db.into(db.bankTransactions).insert(
            BankTransactionsCompanion.insert(
              txnId: bankId,
              accountId: bankAccountId!,
              txnDate: date,
              type: 'DEBIT',
              category:
                  category.isPersonal ? 'OWNER_DRAWING' : category.dbValue,
              amount: Value(amount),
              paymentMode: const Value('AUTO_DEBIT'),
              description: Value(note),
              referenceId: Value(sourceId),
              referenceType: const Value('DAY_BOOK_BALANCE'),
              isAutoGenerated: const Value(true),
            ),
          );
    }
    return sourceId;
  }
}
